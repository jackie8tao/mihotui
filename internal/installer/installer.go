package installer

import (
	"archive/tar"
	"archive/zip"
	"compress/gzip"
	"context"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"time"

	"github.com/jackie8tao/mihotui/internal/config"
)

const (
	DefaultMihomoVersion = "v1.19.33"
	DefaultMihomoRepo    = "MetaCubeX/mihomo"
)

// Options represents parameters for installing Mihomo core.
type Options struct {
	Paths       *config.AppPaths // Resolved suite runtime paths (single source of truth)
	ArchivePath string           // Optional local compressed archive (.gz, .tar.gz, .tgz, .zip)
	Version     string           // Specific version (e.g. v1.19.33) or "latest"
	Mirror      string           // Optional mirror prefix (e.g. https://ghproxy.net/)
	Force       bool             // Force overwrite existing binary
}

// Result contains information about the completed installation.
type Result struct {
	TargetDir    string
	MihomoBin    string
	MihomoConfig string
}

// Install installs the Mihomo core binary and initializes the configuration directory.
func Install(ctx context.Context, opts Options) (*Result, error) {
	if opts.Paths == nil || strings.TrimSpace(opts.Paths.AppRoot) == "" {
		return nil, errors.New("installer: app paths cannot be nil or empty")
	}

	// 1. Resolve Target Paths directly from opts.Paths
	binDir := opts.Paths.BinDir
	mihomoDir := opts.Paths.MihomoDir
	targetBin := opts.Paths.MihomoBin

	if err := os.MkdirAll(binDir, 0755); err != nil {
		return nil, fmt.Errorf("installer: failed to create bin directory %q: %w", binDir, err)
	}
	if err := os.MkdirAll(mihomoDir, 0755); err != nil {
		return nil, fmt.Errorf("installer: failed to create config directory %q: %w", mihomoDir, err)
	}

	// 2. Check if already installed
	if !opts.Force {
		if fi, err := os.Stat(targetBin); err == nil && !fi.IsDir() {
			fmt.Printf("Mihomo core binary already exists at %s (use --force to overwrite)\n", targetBin)
			return &Result{
				TargetDir:    opts.Paths.AppRoot,
				MihomoBin:    targetBin,
				MihomoConfig: filepath.Join(mihomoDir, "config.yaml"),
			}, nil
		}
	}

	// 3. Install core binary from local archive or remote release
	if err := installBinary(ctx, opts, targetBin); err != nil {
		return nil, err
	}

	// 4. Ensure Executable Permissions
	if err := os.Chmod(targetBin, 0755); err != nil {
		return nil, fmt.Errorf("installer: failed to set executable permission: %w", err)
	}

	// 5. Initialize default mihomo config if not exists
	cfgPath := filepath.Join(mihomoDir, "config.yaml")
	if _, err := os.Stat(cfgPath); errors.Is(err, os.ErrNotExist) {
		defaultYAML := `# Default Mihomo configuration generated by mihotui
port: 7890
socks-port: 7891
mixed-port: 7890
allow-lan: false
mode: rule
log-level: info
external-controller: 127.0.0.1:9090
secret: ""
`
		if err := os.WriteFile(cfgPath, []byte(defaultYAML), 0644); err == nil {
			fmt.Printf("==> Initialized default Mihomo configuration at %s\n", cfgPath)
		}
	}

	return &Result{
		TargetDir:    opts.Paths.AppRoot,
		MihomoBin:    targetBin,
		MihomoConfig: cfgPath,
	}, nil
}

func installBinary(ctx context.Context, opts Options, targetBin string) error {
	if archivePath := strings.TrimSpace(opts.ArchivePath); archivePath != "" {
		fmt.Printf("==> Installing Mihomo core from local archive...\n")
		fmt.Printf("    Archive: %s\n", archivePath)
		fmt.Printf("    Target : %s\n", targetBin)

		if err := extractLocalArchive(archivePath, targetBin); err != nil {
			return fmt.Errorf("installer: archive extraction failed: %w", err)
		}
		return nil
	}

	return installFromRemote(ctx, opts, targetBin)
}

func installFromRemote(ctx context.Context, opts Options, targetBin string) error {
	version := resolveDownloadVersion(ctx, opts.Version)

	assetName, err := resolveAssetName(runtime.GOOS, runtime.GOARCH, version)
	if err != nil {
		return fmt.Errorf("installer: unsupported platform %s/%s: %w", runtime.GOOS, runtime.GOARCH, err)
	}

	rawURL := fmt.Sprintf("https://github.com/%s/releases/download/%s/%s", DefaultMihomoRepo, version, assetName)
	downloadURL := rawURL
	if opts.Mirror != "" {
		mirrorPrefix := strings.TrimRight(opts.Mirror, "/")
		downloadURL = fmt.Sprintf("%s/%s", mirrorPrefix, rawURL)
	}

	fmt.Printf("==> Downloading Mihomo core (%s) for %s/%s...\n", version, runtime.GOOS, runtime.GOARCH)
	fmt.Printf("    Source: %s\n", downloadURL)
	fmt.Printf("    Target: %s\n", targetBin)

	if err := downloadAndExtract(ctx, downloadURL, targetBin); err != nil {
		return fmt.Errorf("installer: download failed: %w", err)
	}
	return nil
}

func resolveDownloadVersion(ctx context.Context, requested string) string {
	version := requested
	if version == "" || version == "latest" {
		detectedVer, err := fetchLatestVersion(ctx)
		if err != nil {
			fmt.Printf("Warning: failed to query latest release from GitHub (%v), falling back to %s\n", err, DefaultMihomoVersion)
			return DefaultMihomoVersion
		}
		version = detectedVer
	}

	if !strings.HasPrefix(version, "v") {
		return "v" + version
	}
	return version
}

// resolveAssetName maps OS and architecture to the official MetaCubeX/mihomo release asset name.
func resolveAssetName(goos, goarch, version string) (string, error) {
	switch goos {
	case "linux":
		switch goarch {
		case "amd64":
			return fmt.Sprintf("mihomo-linux-amd64-compatible-%s.gz", version), nil
		case "arm64":
			return fmt.Sprintf("mihomo-linux-arm64-%s.gz", version), nil
		case "arm":
			return fmt.Sprintf("mihomo-linux-armv7-%s.gz", version), nil
		case "386":
			return fmt.Sprintf("mihomo-linux-386-%s.gz", version), nil
		}
	case "darwin":
		switch goarch {
		case "arm64":
			return fmt.Sprintf("mihomo-darwin-arm64-%s.gz", version), nil
		case "amd64":
			return fmt.Sprintf("mihomo-darwin-amd64-compatible-%s.gz", version), nil
		}
	}

	return "", fmt.Errorf("no prebuilt release asset available for %s/%s", goos, goarch)
}

func fetchLatestVersion(ctx context.Context) (string, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodHead, "https://github.com/"+DefaultMihomoRepo+"/releases/latest", nil)
	if err != nil {
		return "", err
	}

	// Disable following redirect automatically to capture Location header
	client := &http.Client{
		CheckRedirect: func(req *http.Request, via []*http.Request) error {
			return http.ErrUseLastResponse
		},
		Timeout: 8 * time.Second,
	}

	resp, err := client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()

	loc := resp.Header.Get("Location")
	if loc == "" {
		return "", errors.New("no redirect location found")
	}

	// Extract tag name from URL, e.g. https://github.com/MetaCubeX/mihomo/releases/tag/v1.19.33
	parts := strings.Split(loc, "/")
	tag := parts[len(parts)-1]
	if tag == "" {
		return "", fmt.Errorf("failed to parse tag from location %q", loc)
	}

	return tag, nil
}

func downloadAndExtract(ctx context.Context, downloadURL, targetBinPath string) error {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, downloadURL, nil)
	if err != nil {
		return err
	}
	req.Header.Set("User-Agent", "mihotui-installer")

	client := &http.Client{
		Timeout: 3 * time.Minute,
	}

	resp, err := client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("HTTP request failed with status %d", resp.StatusCode)
	}

	return extractGzip(resp.Body, targetBinPath)
}

func extractLocalArchive(archivePath, targetBinPath string) error {
	info, err := os.Stat(archivePath)
	if err != nil {
		return err
	}
	if info.IsDir() {
		return fmt.Errorf("%q is a directory, expected a compressed archive file", archivePath)
	}

	lower := strings.ToLower(archivePath)
	switch {
	case strings.HasSuffix(lower, ".tar.gz"), strings.HasSuffix(lower, ".tgz"):
		return extractTarGz(archivePath, targetBinPath)
	case strings.HasSuffix(lower, ".gz"):
		f, err := os.Open(archivePath)
		if err != nil {
			return err
		}
		defer f.Close()
		return extractGzip(f, targetBinPath)
	case strings.HasSuffix(lower, ".zip"):
		return extractZip(archivePath, targetBinPath)
	default:
		return fmt.Errorf("unsupported archive format %q (supported: .gz, .tar.gz, .tgz, .zip)", archivePath)
	}
}

func extractGzip(r io.Reader, targetBinPath string) error {
	// Mihomo releases are individual .gz compressed binaries.
	gzReader, err := gzip.NewReader(r)
	if err != nil {
		return fmt.Errorf("failed to read gzip stream: %w", err)
	}
	defer gzReader.Close()

	return writeBinaryAtomically(gzReader, targetBinPath)
}

func extractTarGz(archivePath, targetBinPath string) error {
	f, err := os.Open(archivePath)
	if err != nil {
		return err
	}
	defer f.Close()

	gzReader, err := gzip.NewReader(f)
	if err != nil {
		return fmt.Errorf("failed to read gzip stream: %w", err)
	}
	defer gzReader.Close()

	tr := tar.NewReader(gzReader)
	for {
		header, err := tr.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return fmt.Errorf("failed to read tar entry: %w", err)
		}
		if header.Typeflag != tar.TypeReg {
			continue
		}
		if isMihomoBinaryCandidate(header.Name) {
			return writeBinaryAtomically(tr, targetBinPath)
		}
	}

	return fmt.Errorf("no mihomo binary found in archive %q", archivePath)
}

func extractZip(archivePath, targetBinPath string) error {
	zr, err := zip.OpenReader(archivePath)
	if err != nil {
		return fmt.Errorf("failed to open zip archive: %w", err)
	}
	defer zr.Close()

	for _, f := range zr.File {
		if f.FileInfo().IsDir() {
			continue
		}
		if !isMihomoBinaryCandidate(f.Name) {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			return fmt.Errorf("failed to open zip entry %q: %w", f.Name, err)
		}
		err = writeBinaryAtomically(rc, targetBinPath)
		_ = rc.Close()
		return err
	}

	return fmt.Errorf("no mihomo binary found in zip archive %q", archivePath)
}

func isMihomoBinaryCandidate(entryName string) bool {
	normalized := filepath.FromSlash(strings.ReplaceAll(entryName, "\\", "/"))
	base := strings.ToLower(filepath.Base(normalized))
	if !strings.HasPrefix(base, "mihomo") {
		return false
	}

	// Skip non-executable auxiliary files that share the mihomo prefix.
	ext := strings.ToLower(filepath.Ext(base))
	switch ext {
	case ".md", ".txt", ".yaml", ".yml", ".json", ".service", ".sh", ".gz", ".zip", ".tgz":
		return false
	}
	return true
}

func writeBinaryAtomically(r io.Reader, targetBinPath string) error {
	tmpPath := targetBinPath + ".tmp"
	tmpFile, err := os.OpenFile(tmpPath, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0755)
	if err != nil {
		return err
	}
	defer func() {
		tmpFile.Close()
		_ = os.Remove(tmpPath)
	}()

	if _, err := io.Copy(tmpFile, r); err != nil {
		return fmt.Errorf("failed to extract binary: %w", err)
	}

	if err := tmpFile.Close(); err != nil {
		return err
	}

	return os.Rename(tmpPath, targetBinPath)
}
