package installer

import (
	"compress/gzip"
	"context"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"time"
)

const (
	DefaultMihomoVersion = "v1.19.33"
	DefaultMihomoRepo    = "MetaCubeX/mihomo"
)

// Options represents parameters for installing Mihomo core.
type Options struct {
	TargetDir string // Base directory of mihotui bundle (e.g. /usr/local/mihotui)
	Version   string // Specific version (e.g. v1.19.33) or "latest"
	Mirror    string // Optional mirror prefix (e.g. https://ghproxy.net/)
	Force     bool   // Force overwrite existing binary
}

// Result contains information about the completed installation.
type Result struct {
	TargetDir    string
	MihomoBin    string
	MihomoConfig string
	Version      string
}

// Install installs the Mihomo core binary and initializes the configuration directory.
func Install(ctx context.Context, opts Options) (*Result, error) {
	if strings.TrimSpace(opts.TargetDir) == "" {
		return nil, errors.New("installer: target directory cannot be empty")
	}

	// 1. Resolve Target Paths
	binDir := filepath.Join(opts.TargetDir, "bin")
	etcDir := filepath.Join(opts.TargetDir, "etc")
	mihomoDir := filepath.Join(etcDir, "mihomo")
	targetBin := filepath.Join(binDir, "mihomo")

	if err := os.MkdirAll(binDir, 0755); err != nil {
		return nil, fmt.Errorf("installer: failed to create bin directory %q: %w", binDir, err)
	}
	if err := os.MkdirAll(mihomoDir, 0755); err != nil {
		return nil, fmt.Errorf("installer: failed to create config directory %q: %w", mihomoDir, err)
	}

	// 2. Check if already installed
	if !opts.Force {
		if fi, err := os.Stat(targetBin); err == nil && !fi.IsDir() {
			fmt.Printf("Mihomo core binary already exists at %s (use --force to overwrite)\n", targetBin)
			verOutput, _ := getInstalledVersion(targetBin)
			return &Result{
				TargetDir:    opts.TargetDir,
				MihomoBin:    targetBin,
				MihomoConfig: filepath.Join(mihomoDir, "config.yaml"),
				Version:      verOutput,
			}, nil
		}
	}

	// 3. Resolve Version and Asset Download URL
	version := opts.Version
	if version == "" || version == "latest" {
		detectedVer, err := fetchLatestVersion(ctx)
		if err != nil {
			fmt.Printf("Warning: failed to query latest release from GitHub (%v), falling back to %s\n", err, DefaultMihomoVersion)
			version = DefaultMihomoVersion
		} else {
			version = detectedVer
		}
	}
	if !strings.HasPrefix(version, "v") {
		version = "v" + version
	}

	assetName, err := ResolveAssetName(runtime.GOOS, runtime.GOARCH, version)
	if err != nil {
		return nil, fmt.Errorf("installer: unsupported platform %s/%s: %w", runtime.GOOS, runtime.GOARCH, err)
	}

	rawURL := fmt.Sprintf("https://github.com/%s/releases/download/%s/%s", DefaultMihomoRepo, version, assetName)
	downloadURL := rawURL
	if opts.Mirror != "" {
		mirrorPrefix := strings.TrimRight(opts.Mirror, "/")
		downloadURL = fmt.Sprintf("%s/%s", mirrorPrefix, rawURL)
	}

	fmt.Printf("==> Downloading Mihomo core (%s) for %s/%s...\n", version, runtime.GOOS, runtime.GOARCH)
	fmt.Printf("    Source: %s\n", downloadURL)
	fmt.Printf("    Target: %s\n", targetBin)

	// 4. Download and unpack
	if err := downloadAndExtract(ctx, downloadURL, targetBin); err != nil {
		return nil, fmt.Errorf("installer: download failed: %w", err)
	}

	// 5. Ensure Executable Permissions
	if err := os.Chmod(targetBin, 0755); err != nil {
		return nil, fmt.Errorf("installer: failed to set executable permission: %w", err)
	}

	// 6. Verify Installation
	verOutput, err := getInstalledVersion(targetBin)
	if err != nil {
		fmt.Printf("Warning: installed binary verification failed: %v\n", err)
	} else {
		fmt.Printf("==> Mihomo verified: %s\n", verOutput)
	}

	// 7. Initialize default mihomo config if not exists
	cfgPath := filepath.Join(mihomoDir, "config.yaml")
	if _, err := os.Stat(cfgPath); errors.Is(err, os.ErrNotExist) {
		defaultYAML := `# Default Mihomo configuration generated by mihotui
port: 7890
socks-port: 7891
mixed-port: 7890
allow-lan: false
mode: rule
log-level: info
external-controller: 127.0.0.1:9090
secret: ""
`
		if err := os.WriteFile(cfgPath, []byte(defaultYAML), 0644); err == nil {
			fmt.Printf("==> Initialized default Mihomo configuration at %s\n", cfgPath)
		}
	}

	return &Result{
		TargetDir:    opts.TargetDir,
		MihomoBin:    targetBin,
		MihomoConfig: cfgPath,
		Version:      verOutput,
	}, nil
}

// ResolveAssetName maps OS and architecture to the official MetaCubeX/mihomo release asset name.
func ResolveAssetName(goos, goarch, version string) (string, error) {
	switch goos {
	case "linux":
		switch goarch {
		case "amd64":
			return fmt.Sprintf("mihomo-linux-amd64-compatible-%s.gz", version), nil
		case "arm64":
			return fmt.Sprintf("mihomo-linux-arm64-%s.gz", version), nil
		case "arm":
			return fmt.Sprintf("mihomo-linux-armv7-%s.gz", version), nil
		case "386":
			return fmt.Sprintf("mihomo-linux-386-%s.gz", version), nil
		}
	case "darwin":
		switch goarch {
		case "arm64":
			return fmt.Sprintf("mihomo-darwin-arm64-%s.gz", version), nil
		case "amd64":
			return fmt.Sprintf("mihomo-darwin-amd64-compatible-%s.gz", version), nil
		}
	}

	return "", fmt.Errorf("no prebuilt release asset available for %s/%s", goos, goarch)
}

func fetchLatestVersion(ctx context.Context) (string, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodHead, "https://github.com/"+DefaultMihomoRepo+"/releases/latest", nil)
	if err != nil {
		return "", err
	}

	// Disable following redirect automatically to capture Location header
	client := &http.Client{
		CheckRedirect: func(req *http.Request, via []*http.Request) error {
			return http.ErrUseLastResponse
		},
		Timeout: 8 * time.Second,
	}

	resp, err := client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()

	loc := resp.Header.Get("Location")
	if loc == "" {
		return "", errors.New("no redirect location found")
	}

	// Extract tag name from URL, e.g. https://github.com/MetaCubeX/mihomo/releases/tag/v1.19.33
	parts := strings.Split(loc, "/")
	tag := parts[len(parts)-1]
	if tag == "" {
		return "", fmt.Errorf("failed to parse tag from location %q", loc)
	}

	return tag, nil
}

func downloadAndExtract(ctx context.Context, downloadURL, targetBinPath string) error {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, downloadURL, nil)
	if err != nil {
		return err
	}
	req.Header.Set("User-Agent", "mihotui-installer")

	client := &http.Client{
		Timeout: 3 * time.Minute,
	}

	resp, err := client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("HTTP request failed with status %d", resp.StatusCode)
	}

	tmpPath := targetBinPath + ".tmp"
	tmpFile, err := os.OpenFile(tmpPath, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0755)
	if err != nil {
		return err
	}
	defer func() {
		tmpFile.Close()
		_ = os.Remove(tmpPath)
	}()

	// Mihomo releases are individual .gz compressed binaries
	gzReader, err := gzip.NewReader(resp.Body)
	if err != nil {
		return fmt.Errorf("failed to read gzip stream: %w", err)
	}
	defer gzReader.Close()

	if _, err := io.Copy(tmpFile, gzReader); err != nil {
		return fmt.Errorf("failed to extract binary: %w", err)
	}

	if err := tmpFile.Close(); err != nil {
		return err
	}

	return os.Rename(tmpPath, targetBinPath)
}

func getInstalledVersion(binPath string) (string, error) {
	cmd := exec.Command(binPath, "-v")
	out, err := cmd.CombinedOutput()
	if err != nil {
		return "", err
	}
	line := strings.TrimSpace(string(out))
	if idx := strings.Index(line, "\n"); idx != -1 {
		line = line[:idx]
	}
	return line, nil
}

